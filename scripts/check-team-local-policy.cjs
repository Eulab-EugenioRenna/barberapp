// Disposable PostgreSQL/domain test. No Connect requests, user login or production records.
const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');
const { execFileSync } = require('node:child_process');
const fs = require('node:fs');
const path = require('node:path');
const { PrismaClient } = require('@prisma/client');
const url = new URL(process.env.DATABASE_URL || 'http://invalid');
if (!/^\/barber_team_policy_test_[0-9]+$/.test(url.pathname)) throw Error('Use an isolated barber_team_policy_test_<digits> database only');
const work = path.join('.local', path.basename(url.pathname));
const migration = '20261025000000_user_permissions_configured';
const prisma = new PrismaClient();
const run = (args, extra = {}) => execFileSync(process.execPath, args, { stdio: 'inherit', env: { ...process.env, ...extra } });
async function main() {
  fs.mkdirSync(work, { recursive: true, mode: 0o700 });
  const [{ empty }] = await prisma.$queryRaw`SELECT to_regclass('public."User"') IS NULL AS empty`;
  assert.equal(empty, true, 'Fixture database must be empty');
  fs.cpSync('prisma', path.join(work, 'prisma'), { recursive: true });
  fs.rmSync(path.join(work, 'prisma/migrations', migration), { recursive: true });
  run(['node_modules/prisma/build/index.js', 'migrate', 'deploy', '--schema', path.join(work, 'prisma/schema.prisma')]);
  const company = randomUUID(), foreignCompany = randomUUID(), target = randomUUID(), other = randomUUID(), professional = randomUUID(), spare = randomUUID(), occupied = randomUUID(), foreign = randomUUID();
  for (const id of [company, foreignCompany]) await prisma.$executeRaw`INSERT INTO "Tenant" (id,name,slug,"updatedAt") VALUES(${id},'Synthetic fixture',${id},now())`;
  for (const id of [target, other]) await prisma.$executeRaw`INSERT INTO "User" (id,"tenantId",email,"firstName","lastName",role,permissions,"passwordHash","updatedAt") VALUES(${id},${company},${id+'@example.test'},'Synthetic','Fixture','collaborator',ARRAY[]::text[],'synthetic-preserved-hash',now())`;
  for (const [id, tenant, userId] of [[professional, company, null], [spare, company, null], [occupied, company, other], [foreign, foreignCompany, null]]) await prisma.$executeRaw`INSERT INTO "Collaborator" (id,"tenantId","userId","firstName","lastName") VALUES(${id},${tenant},${userId},'Synthetic','Professional')`;
  const checkpoint = path.join(work, 'checkpoint.json');
  run(['scripts/team-policy-migration.cjs', 'analyze', checkpoint]);
  run(['scripts/team-policy-migration.cjs', 'apply', checkpoint], { ALORA_MIGRATION_WRITES_FROZEN: '1' });
  run(['scripts/team-policy-migration.cjs', 'verify', checkpoint]);
  const original = await prisma.user.findUniqueOrThrow({ where: { id: target } });
  assert.equal(original.permissionsConfigured, false);
  assert.equal(original.passwordHash, 'synthetic-preserved-hash');
  const { ALORA_FUNCTIONS, canUseLocalFunction } = require('../dist/apps/api/common/function-catalog.js');
  assert.equal(canUseLocalFunction({ ...original, collaboratorId: professional }, 'appointments.read.own'), true);
  const { TeamLocalPolicyService } = require('../dist/apps/api/modules/team/team-local-policy.service.js');
  const allKeys = ALORA_FUNCTIONS.map(fn => fn.key), own = ['appointments.read.own', 'appointments.update.own'];
  const actor = { id: randomUUID(), tenantId: company, role: 'owner', connectFunctions: allKeys };
  const overview = { installationId: 'synthetic-installation', canManage: true, functions: allKeys.map(key => ({ key, delegable: true })), delegation: allKeys.map(key => ({ key })), roles: [{ id: 'synthetic-role', permissions: own }], users: [{ localUserId: target, subject: 'synthetic-subject', roles: [{ id: 'synthetic-role' }] }] };
  const team = { withTeam: (_authorization, operation) => operation({ teamOverview: async () => overview }, 'synthetic-token', { user: actor, tenantId: company }) };
  const service = new TeamLocalPolicyService(prisma, team);
  const body = { role: 'collaborator', permissions: own, collaboratorId: professional };
  await assert.rejects(service.save(undefined, target, { ...body, collaboratorId: foreign }), /Professionista non disponibile/);
  await assert.rejects(service.save(undefined, target, { ...body, collaboratorId: occupied }), /già associato/);
  assert.equal((await prisma.collaborator.findUniqueOrThrow({ where: { id: occupied } })).userId, other);
  await prisma.collaborator.update({ where: { id: foreign }, data: { userId: target } });
  await assert.rejects(service.save(undefined, target, { role: 'collaborator', permissions: [], collaboratorId: null }), /Associazione precedente/);
  assert.equal((await prisma.collaborator.findUniqueOrThrow({ where: { id: foreign } })).userId, target);
  await prisma.collaborator.update({ where: { id: foreign }, data: { userId: null } });

  const saved = await service.save(undefined, target, body);
  assert.equal(saved.permissionsConfigured, true);assert.equal(saved.collaborator.id, professional);
  assert.equal(canUseLocalFunction({ ...saved, collaboratorId: professional }, 'appointments.read.own'), true);
  const failing = prisma.$extends({ query: { user: { async update() { throw Error('synthetic policy write failure'); } } } });
  const failingService = new TeamLocalPolicyService(failing, team);
  await assert.rejects(failingService.save(undefined, target, { ...body, collaboratorId: spare }), /synthetic policy write failure/);
  assert.equal((await prisma.collaborator.findUniqueOrThrow({ where: { id: professional } })).userId, target, 'Old association must survive rollback');
  assert.equal((await prisma.collaborator.findUniqueOrThrow({ where: { id: spare } })).userId, null, 'New association must roll back');

  await service.save(undefined, target, { role: 'collaborator', permissions: [], collaboratorId: null });
  const denied = await prisma.user.findUniqueOrThrow({ where: { id: target }, include: { collaborator: true } });
  assert.equal(denied.collaborator, null);assert.equal(denied.passwordHash, original.passwordHash);
  assert.equal(canUseLocalFunction({ ...denied, collaboratorId: professional }, 'appointments.read.own'), false);
  await assert.rejects(service.save(undefined, target, { ...body, permissions: ['dashboard.revenue.read'] }), /restrizioni locali/);
  overview.roles[0].permissions.push('unlicensed.outside.delegation');
  await assert.rejects(service.save(undefined, target, { role: 'collaborator', permissions: [] }), /privilegi fuori/);
  overview.roles[0].permissions.pop();
  actor.tenantId = foreignCompany;
  team.withTeam = (_authorization, operation) => operation({ teamOverview: async () => overview }, 'synthetic-token', { user: actor, tenantId: foreignCompany });
  await assert.rejects(service.save(undefined, target, body), /Account locale non modificabile/);
  actor.tenantId = company;
  team.withTeam = (_authorization, operation) => operation({ teamOverview: async () => overview }, 'synthetic-token', { user: actor, tenantId: company });
  await prisma.user.update({ where: { id: target }, data: { role: 'owner' } });
  await assert.rejects(service.save(undefined, target, body), /Account locale non modificabile/);
  console.log('PASS: additive migration reconciliation, preserved legacy policy/hash, explicit empty policy, scoped links, collision rejection, transaction rollback, owner protection, delegation and cross-tenant rejection. Synthetic PostgreSQL fixture only.');
}
main().catch(error => { console.error(error.message); process.exitCode = 1; }).finally(() => prisma.$disconnect());
